let currentLanguage = "en";

function setLanguage(language) {
  currentLanguage = language;
  const dictionary = translations[language];

  // Update all translated elements while preserving the surrounding HTML structure.
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    if (dictionary[key]) element.textContent = dictionary[key];
  });

  document.documentElement.lang = language;
  document.title = language === "fr"
    ? "Ferdaous Abe — Étudiante en développement d’applications"
    : "Ferdaous Abe — Software Engineering Student";

  const toggle = document.getElementById("language-toggle");
  toggle.textContent = language === "en" ? "FR" : "EN";
  toggle.setAttribute("aria-label", language === "en" ? "Passer en français" : "Switch to English");

  // Update accessible menu labels for the selected language.
  updateMenuLabel();
}

function updateMenuLabel() {
  const menuToggle = document.getElementById("menu-toggle");
  const dictionary = translations[currentLanguage];
  const isOpen = menuToggle.getAttribute("aria-expanded") === "true";
  menuToggle.setAttribute("aria-label", isOpen ? dictionary.menu_close : dictionary.menu_open);
}

function setupMobileMenu() {
  const toggle = document.getElementById("menu-toggle");
  const links = document.getElementById("nav-links");

  function closeMenu() {
    toggle.setAttribute("aria-expanded", "false");
    links.classList.remove("is-open");
    document.body.classList.remove("menu-open");
    updateMenuLabel();
  }

  toggle.addEventListener("click", () => {
    const willOpen = toggle.getAttribute("aria-expanded") !== "true";
    toggle.setAttribute("aria-expanded", String(willOpen));
    links.classList.toggle("is-open", willOpen);
    document.body.classList.toggle("menu-open", willOpen);
    updateMenuLabel();
  });

  // Close the mobile menu after a section link is selected.
  links.querySelectorAll('a[href^="#"]').forEach((link) => {
    link.addEventListener("click", closeMenu);
  });

  // Restore the desktop navigation if the viewport becomes wider.
  window.addEventListener("resize", () => {
    if (window.innerWidth > 680) closeMenu();
  });

  document.addEventListener("keydown", (event) => {
    if (event.key === "Escape") closeMenu();
  });
}

function renderContactLinks() {
  const container = document.getElementById("contact-links");
  const dictionary = translations[currentLanguage];
  const items = [
    { name: "GitHub", value: CONTACT.github, aria: dictionary.github_aria },
    { name: "LinkedIn", value: CONTACT.linkedin, aria: dictionary.linkedin_aria },
    { name: dictionary.email_label, value: CONTACT.email ? `mailto:${CONTACT.email}` : "", aria: dictionary.email_aria, email: true }
  ];

  container.replaceChildren();
  items.forEach((item) => {
    if (item.value) {
      const link = document.createElement("a");
      link.className = "contact-placeholder contact-link";
      link.href = item.value;
      link.setAttribute("aria-label", item.aria);
      if (!item.email) {
        link.target = "_blank";
        link.rel = "noopener noreferrer";
      }
      link.textContent = item.name;
      container.appendChild(link);
    } else {
      const placeholder = document.createElement("span");
      placeholder.className = "contact-placeholder";
      const name = document.createTextNode(item.name + " ");
      const small = document.createElement("small");
      small.textContent = dictionary.link_add_later;
      placeholder.append(name, small);
      container.appendChild(placeholder);
    }
  });
}

