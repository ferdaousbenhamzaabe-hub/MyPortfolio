async function fetchGitHubProjects() {
  const gridContainer = document.getElementById("project-grid");
  const username = "ferdaousbenhamzaabe-hub";

  try {
    const response = await fetch(`https://api.github.com/users/${username}/repos?sort=updated&per_page=6`);
    if (!response.ok) throw new Error("Erreur réseau");
    
    const repos = await response.json();
    const filteredRepos = repos.filter(repo => repo.name !== "portfolio" && !repo.fork);

    if (filteredRepos.length === 0) {
      gridContainer.innerHTML = "<p style='color: var(--text-2);'>Aucun projet trouvé sur GitHub pour le moment.</p>";
      return;
    }

    gridContainer.replaceChildren();

    filteredRepos.forEach(repo => {
      const article = document.createElement("article");
      article.className = "project-card";

      // Gestion de l'image de prévisualisation
      let imageUrl = "";
      
      // Vérification si le projet est Blackjack (insensible à la casse)
      if (repo.name.toLowerCase().includes("blackjack")) {
        imageUrl = "images/blackjack-Game.png";
      } else {
        // Pour les autres projets, recherche d'un fichier preview.png sur le dépôt GitHub
        imageUrl = `https://raw.githubusercontent.com/${username}/${repo.name}/${repo.default_branch}/preview.png`;
      }

      const visualDiv = document.createElement("div");
      visualDiv.className = "project-visual";
      visualDiv.setAttribute("aria-hidden", "true");

      const img = document.createElement("img");
      img.src = imageUrl;
      img.alt = repo.name;
      img.style.width = "100%";
      img.style.height = "100%";
      img.style.objectFit = "cover";

      // Image de remplacement texte/titre au cas où l'image ne charge pas
      img.onerror = () => {
        visualDiv.innerHTML = `<span class="table-label" style="font-size: 0.8rem; font-weight: bold; letter-spacing: 0.1em; color: var(--accent);">${repo.name.toUpperCase()}</span>`;
      };

      visualDiv.appendChild(img);

      const infoDiv = document.createElement("div");
      infoDiv.className = "project-info";
      
      const language = repo.language || "Multi-tech";
      const description = repo.description || "Projet hébergé sur GitHub.";

      infoDiv.innerHTML = `
        <div class="project-topline">
          <span class="project-type">GITHUB REPOSITORY</span>
          <span class="project-status status-done">Built</span>
        </div>
        <h3><a href="${repo.html_url}" target="_blank" rel="noopener noreferrer">${repo.name}</a></h3>
        <p>${description}</p>
        <div class="project-footer">
          <span class="project-tech">${language}</span>
          <a href="${repo.html_url}" target="_blank" rel="noopener noreferrer" class="project-arrow" aria-label="Voir le dépôt GitHub">↗</a>
        </div>
      `;

      article.appendChild(visualDiv);
      article.appendChild(infoDiv);
      gridContainer.appendChild(article);
    });

  } catch (error) {
    console.error("Erreur GitHub API:", error);
    gridContainer.innerHTML = "<p style='color: var(--text-2);'>Impossible de charger les projets depuis GitHub pour le moment.</p>";
  }
}

fetchGitHubProjects();

